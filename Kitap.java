public class Kitap {
    private String ad;
    private String yazar;
    private String isbn;

    public Kitap(String ad, String yazar, String isbn) {
        this.ad = ad;
        this.yazar = yazar;
        this.isbn = isbn;
    }

    public String getAd() {
        return ad;
    }

    public String getYazar() {
        return yazar;
    }

    public String getIsbn() {
        return isbn;
    }
}

    

